const DICTS: Record<Locale, Record<string, string>> = {
  en: { ...en, ...EX_EN },
  fr: { ...fr, ...EX_FR },
  es: { ...es, ...EX_ES },
  ru: { ...ru, ...EX_RU },
  zh: { ...zh, ...EX_ZH },
  ja: { ...ja, ...EX_JA },
};

let current = $state<Locale>(getPrefs().locale);

/** The active locale (reactive). */
export function locale(): Locale {
  return current;
}

/** Switch language and persist the choice. */
export function setLocale(l: Locale): void {
  current = l;
  setPrefs({ ...getPrefs(), locale: l });
}

/** Translate a key for the active locale, falling back to English then the key. */
export function t(key: TKey): string {
  return DICTS[current][key as string] ?? DICTS.en[key as string] ?? (key as string);
}
